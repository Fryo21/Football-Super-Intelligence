
import hashlib
import json


class FootysimAdapter:
    SCHEMA_VERSION = "1.0.0"

    def __init__(self, match_data):
        self.match_data = match_data
        self.match_id = self._create_match_id()

    def _create_match_id(self):
        """Generate a consistent match ID from simulator metadata."""

        match_metadata = self.match_data["meta"]

        # Exclude the final score from the match identity.
        metadata_without_final_score = {
            field_name: field_value
            for field_name, field_value in match_metadata.items()
            if field_name != "final_score"
        }

        # Convert match information into a consistent JSON string.
        match_identity = {
            "source": "footysim",
            "metadata": metadata_without_final_score
        }

        match_identity_json = json.dumps(
            match_identity,
            sort_keys=True
        )

        # Encode the JSON string before generating its hash.
        match_identity_bytes = match_identity_json.encode("utf-8")

        match_hash = hashlib.sha256(
            match_identity_bytes
        ).hexdigest()

        return "fsi_" + match_hash[:16]

    def _create_event_id(self, event_index):
        """Generate a consistent ID from the match ID and event position."""

        event_identity = (
            f"{self.match_id}:events_general:{event_index}"
        )

        event_identity_bytes = event_identity.encode("utf-8")

        event_hash = hashlib.sha256(
            event_identity_bytes
        ).hexdigest()

        return event_hash[:20]

    def transform_events(self):
        """Convert Footysim events into the FSI canonical event format."""

        normalized_events = []

        # Fields already mapped to the canonical schema.
        known_event_fields = {
            "actor",
            "receiver",
            "target",
            "team",
            "type",
            "t",
            "tick",
            "half",
            "loc",
            "distance",
            "pressure",
            "outcome",
            "xg"
        }

        # Process each event generated by the simulator.
        for event_index, match_event in enumerate(
            self.match_data["events_general"]
        ):

            # Preserve additional simulator fields.
            additional_event_properties = {
                field_name: field_value
                for field_name, field_value in match_event.items()
                if field_name not in known_event_fields
            }

            # Map simulator fields to the FSI canonical schema.
            normalized_event = {
                "schema_version": self.SCHEMA_VERSION,
                "event_id": self._create_event_id(event_index),
                "match_id": self.match_id,
                "source": "footysim",

                "event_type": match_event["type"],
                "match_second": match_event["t"],
                "tick": match_event["tick"],
                "half": match_event["half"],

                "team_id": match_event.get("team"),
                "player_id": match_event.get("actor"),
                "target_player_id": match_event.get(
                    "receiver",
                    match_event.get("target")
                ),

                "event_location": match_event.get("loc"),
                "distance": match_event.get("distance"),
                "pressure": match_event.get("pressure"),
                "outcome": match_event.get("outcome"),
                "xg": match_event.get("xg"),

                "properties": additional_event_properties
            }

            normalized_events.append(normalized_event)

        return normalized_events
        
    def _create_frame_id(self, frame_index):
        """Create a stable identifier for a tracking frame."""

        frame_identity = (
            f"{self.match_id}:frames:{frame_index}"
        )

        return hashlib.sha256(
            frame_identity.encode("utf-8")
        ).hexdigest()[:20]

    def transform_frames(self):
        """Convert Footysim tracking frames to the FSI format."""

        normalized_frames = []

        for frame_index, frame in enumerate(
            self.match_data["frames"]
        ):
            normalized_frame = {
                "schema_version": self.SCHEMA_VERSION,
                "frame_id": self._create_frame_id(frame_index),
                "match_id": self.match_id,
                "source": "footysim",
                "match_second": frame["t"],
                "tick": frame["tick"],
                "ball_position": frame["ball"],
                "ball_owner_id": frame.get("owner"),
                "player_positions": frame["players"]
            }

            normalized_frames.append(normalized_frame)

        return normalized_frames

    
    def transform_metadata(self):
        """Normalize match metadata without exposing the final result."""

        metadata = self.match_data["meta"]

        return {
            "schema_version": self.SCHEMA_VERSION,
            "match_id": self.match_id,
            "source": "footysim",
            "engine": metadata["engine"],
            "seed": metadata["seed"],
            "config": metadata["config"],
            "teams": metadata["teams"]
        }

